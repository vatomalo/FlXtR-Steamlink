def rows_for(char):
    return GLYPHS.get(char.upper(), GLYPHS[" "])


def main():
    for glyph in GLYPHS.values():
        assert len(glyph) == 7 and all(len(row) == 5 for row in glyph), glyph
    print("/* Generated by tools/gen_som_overlay_font.py. 5x7, bit 4 = left. */")
    print("#ifndef FLXTR_SOM_OVERLAY_FONT_H")
    print("#define FLXTR_SOM_OVERLAY_FONT_H")
    print("#include <stdint.h>")
    print("static const uint8_t som_overlay_font[95][7]={")
    for code in range(32, 127):
        bits = [int(row.replace("#", "1").replace(".", "0"), 2) for row in rows_for(chr(code))]
