#!/usr/bin/env python3
"""Build original indexed starter poses. No ROM input."""
import sys

OUTLINE, CLOTH, SHADOW, BOOTS, HAIR, HAIR_LIGHT, SKIN, SKIN_SHADE, EYE, SCARF = range(1, 11)


def body(slot, step):
    pixels = [0] * (16 * 32)

    def rect(x, y, w, h, ink):
        for row in range(y, y+h):
            pixels[row*16+x:row*16+x+w] = [ink]*w

    top = 3 + slot
    rect(5, top-1, 6, 1, OUTLINE)
    rect(4, top, 8, 9, OUTLINE)
    rect(5, top+1, 6, 4, HAIR)
    rect(6, top, 3, 2, HAIR_LIGHT)
    if slot == 1:
        rect(3, top+2, 2, 9, HAIR)
        rect(11, top+2, 2, 9, HAIR)
        rect(3, top+4, 1, 4, HAIR_LIGHT)
    elif slot == 2:
        rect(6, top-3, 4, 3, HAIR_LIGHT)
        rect(5, top+2, 6, 1, SCARF)
    rect(5, top+5, 6, 4, SKIN)
    rect(5, top+7, 1, 2, SKIN_SHADE)
    rect(6, top+6, 1, 1, EYE)
    rect(9, top+6, 1, 1, EYE)
    rect(3, 14, 10, 12, OUTLINE)
    rect(4, 15, 8, 10, CLOTH)
    rect(5, 18, 2, 6, SHADOW)
    rect(4, 15, 8, 2, SCARF)
    rect(9, 17, 2, 3, SCARF)
    rect(2, 18+step, 2, 4, SKIN_SHADE)
    rect(12, 19-step, 2, 4, SKIN)
    if slot == 1:
        rect(3, 23, 10, 3, SHADOW)
        rect(4, 23, 8, 1, CLOTH)
    elif slot == 2:
        rect(5, 19, 6, 4, SHADOW)
        rect(7, 19, 2, 2, SCARF)
    rect(4, 25, 3, 5+step, BOOTS)
    rect(9, 25, 3, 6-step, BOOTS)
    return pixels


def main():
    print("/* Generated by tools/som_make_starter_body.py. Original diagnostic art. */")
    print("static const uint8_t som_starter_pixels[3][2][512]={")
    for slot in range(3):
        print("    {")
        for step in range(2):
            print("        {")
            data = body(slot, step)
            for offset in range(0, len(data), 32):
                print("            "+",".join(map(str, data[offset:offset+32]))+",")
            print("        },")
        print("    },")
    print("};")
    print("static const uint8_t som_starter_tiles[3][2][8][64]={")
    for slot in range(3):
        print("    {")
        for step in range(2):
            print("        {")
            data = body(slot, step)
            for ty in range(4):
                for tx in range(2):
                    tile = [data[y*16+x] for y in range(ty*8, (ty+1)*8)
                            for x in range(tx*8, (tx+1)*8)]
                    print("            {"+",".join(map(str, tile))+"},")
            print("        },")
        print("    },")
    print("};")



if __name__ == "__main__":
    main()
